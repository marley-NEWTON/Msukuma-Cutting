/* ── STATE ───────────────────────────────────────────────────────── */
let currentLang = 'en';

/* ── APPLY LANGUAGE ─────────────────────────────────────────────── */
function applyLang(lang) {
  const t = i18n[lang];

  // All elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (!t[key]) return;
    // Use innerHTML for keys that may contain HTML tags
    const htmlKeys = ['hero_title', 'hero_sub'];
    if (htmlKeys.includes(key)) {
      el.innerHTML = t[key];
    } else {
      el.textContent = t[key];
    }
  });

  // Placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (t[key]) el.setAttribute('placeholder', t[key]);
  });

  // Select option placeholders
  const svcSel = document.getElementById('f-service');
  if (svcSel && svcSel.options[0]) {
    svcSel.options[0].text = t['form_service_ph'];
  }

  // Lang toggle label
  document.getElementById('lang-toggle').textContent = t['lang_btn'];

  // Update html lang attribute
  document.documentElement.lang = lang === 'sw' ? 'sw' : 'en';
}

/* ── LANGUAGE TOGGLE ────────────────────────────────────────────── */
document.getElementById('lang-toggle').addEventListener('click', () => {
  currentLang = currentLang === 'en' ? 'sw' : 'en';
  applyLang(currentLang);
});

// Init
applyLang('en');

