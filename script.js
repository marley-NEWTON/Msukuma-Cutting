/* ── MOBILE MENU ────────────────────────────────────────────────── */
const menuToggle  = document.getElementById('menu-toggle');
const mobileMenu  = document.getElementById('mobile-menu');

menuToggle.addEventListener('click', () => {
  const open = mobileMenu.classList.toggle('open');
  menuToggle.classList.toggle('open', open);
  document.body.style.overflow = open ? 'hidden' : '';
});

function closeMobile() {
  mobileMenu.classList.remove('open');
  menuToggle.classList.remove('open');
  document.body.style.overflow = '';
}

/* ── FORM VALIDATION ────────────────────────────────────────────── */
document.getElementById('booking-form').addEventListener('submit', function(e) {
  e.preventDefault();
  const t = i18n[currentLang];
  let valid = true;

  const name    = document.getElementById('f-name');
  const phone   = document.getElementById('f-phone');
  const service = document.getElementById('f-service');
  const date    = document.getElementById('f-date');
  const message = document.getElementById('f-message'); // added (optional but useful)

  const fgName    = document.getElementById('fg-name');
  const fgPhone   = document.getElementById('fg-phone');
  const fgService = document.getElementById('fg-service');
  const fgDate    = document.getElementById('fg-date');

  // Reset
  [fgName, fgPhone, fgService, fgDate].forEach(g => g.classList.remove('invalid'));

  if (!name.value.trim()) {
    fgName.classList.add('invalid');
    fgName.querySelector('.form-error').textContent = t.err_name;
    valid = false;
  }

  const phoneReg = /^\+?255\d{9}$/;
  const cleanPhone = phone.value.trim().replace(/\s+/g, '');
  if (!phoneReg.test(cleanPhone)) {
    fgPhone.classList.add('invalid');
    fgPhone.querySelector('.form-error').textContent = t.err_phone;
    valid = false;
  }

  if (!service.value) {
    fgService.classList.add('invalid');
    fgService.querySelector('.form-error').textContent = t.err_service;
    valid = false;
  }

  if (!date.value) {
    fgDate.classList.add('invalid');
    fgDate.querySelector('.form-error').textContent = t.err_date;
    valid = false;
  }

  /* ── IF VALID → SEND TO WHATSAPP ─────────────────────────────── */
  if (valid) {

    const phoneNumber = "255743261734";

    const text = `
New Booking - Msukuma Cutting TZ

Name: ${name.value}
Phone: ${phone.value}
Service: ${service.value}
Date: ${date.value}
Message: ${message ? message.value : "N/A"}
`;

    const url = `https://wa.me/${phoneNumber}?text=${encodeURIComponent(text)}`;

    // open whatsapp
    window.open(url, "_blank");

    // success message (your existing UI)
    const success = document.getElementById('form-success');
    success.textContent = t.form_success;
    success.style.display = 'block';

    this.reset();

    setTimeout(() => {
      success.style.display = 'none';
    }, 6000);
  }
});

/* ── SET MIN DATE ────────────────────────────────────────────────── */
(function() {
  const dateInput = document.getElementById('f-date');
  const today = new Date();
  const yyyy = today.getFullYear();
  const mm = String(today.getMonth() + 1).padStart(2, '0');
  const dd = String(today.getDate()).padStart(2, '0');
  dateInput.setAttribute('min', `${yyyy}-${mm}-${dd}`);
})();